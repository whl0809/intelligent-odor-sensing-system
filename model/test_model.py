import json
import math
import re
from collections import Counter
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd


# =============================================================================
# User setting: change this filename to the CSV you want to test
# =============================================================================

BASE_DIR = Path(__file__).resolve().parent

TEST_CSV = BASE_DIR / "enose_test.csv"

CLASSIFICATION_DIR = BASE_DIR / "classification_outputs"
MODEL_DIR = CLASSIFICATION_DIR / "models"

METADATA_FILE = (
    CLASSIFICATION_DIR
    / "dataset_and_preprocessing_metadata.json"
)

MODEL_FILES = {
    "combined_class": (
        MODEL_DIR / "combined_class_best_model.joblib"
    ),
    "food_type": (
        MODEL_DIR / "food_type_best_model.joblib"
    ),
    "freshness": (
        MODEL_DIR / "freshness_best_model.joblib"
    ),
}

TEST_OUTPUT_DIR = CLASSIFICATION_DIR / "test_outputs"
WINDOW_OUTPUT_FILE = (
    TEST_OUTPUT_DIR / "test_window_predictions.csv"
)
SUMMARY_OUTPUT_FILE = (
    TEST_OUTPUT_DIR / "test_overall_prediction.json"
)

STATUS_COLUMNS = [
    "ads7828_ok",
    "nh3_ok",
    "h2s_ok",
]


# =============================================================================
# CSV loading and preprocessing
# =============================================================================

def parse_bool_series(series: pd.Series) -> pd.Series:
    if pd.api.types.is_bool_dtype(series):
        return series.fillna(False)

    values = (
        series.astype(str)
        .str.strip()
        .str.lower()
    )

    return values.isin(
        {"true", "1", "yes", "ok"}
    )


def read_test_csv(path: Path) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(
            f"Cannot find test CSV:\n{path}\n\n"
            "Change TEST_CSV at the top of test_model.py, or rename "
            "your new measurement file to enose_test.csv."
        )

    frame = pd.read_csv(path)

    if frame.empty:
        raise ValueError(
            f"Test CSV is empty: {path}"
        )

    if "timestamp_utc" in frame.columns:
        frame["timestamp_utc"] = pd.to_datetime(
            frame["timestamp_utc"],
            utc=True,
            errors="coerce",
        )
        frame = frame.sort_values(
            "timestamp_utc"
        )

    return frame.reset_index(drop=True)


def filter_valid_rows(
    raw_frame: pd.DataFrame,
    selected_channels: dict[str, str],
) -> pd.DataFrame:
    missing_columns = [
        source_column
        for source_column in selected_channels.values()
        if source_column not in raw_frame.columns
    ]

    if missing_columns:
        raise ValueError(
            "The test CSV is missing sensor column(s):\n"
            + "\n".join(missing_columns)
        )

    valid_mask = pd.Series(
        True,
        index=raw_frame.index,
    )

    for status_column in STATUS_COLUMNS:
        if status_column in raw_frame.columns:
            valid_mask &= parse_bool_series(
                raw_frame[status_column]
            )

    cleaned = pd.DataFrame(
        index=raw_frame.index
    )

    for sensor_name, source_column in (
        selected_channels.items()
    ):
        cleaned[sensor_name] = pd.to_numeric(
            raw_frame[source_column],
            errors="coerce",
        )

    valid_mask &= cleaned.notna().all(axis=1)

    if "timestamp_utc" in raw_frame.columns:
        cleaned.insert(
            0,
            "timestamp_utc",
            raw_frame["timestamp_utc"],
        )

    if "elapsed_s" in raw_frame.columns:
        insert_position = (
            1
            if "timestamp_utc" in cleaned.columns
            else 0
        )
        cleaned.insert(
            insert_position,
            "elapsed_s",
            pd.to_numeric(
                raw_frame["elapsed_s"],
                errors="coerce",
            ),
        )

    cleaned = cleaned.loc[
        valid_mask
    ].reset_index(drop=True)

    if cleaned.empty:
        raise ValueError(
            "No valid rows remain after checking status flags "
            "and missing sensor values."
        )

    return cleaned


def normalize_sensor_frame(
    clean_frame: pd.DataFrame,
    baseline_means: dict[str, float],
    baseline_scales: dict[str, float],
) -> pd.DataFrame:
    normalized = clean_frame.copy()

    metadata_columns = {
        "timestamp_utc",
        "elapsed_s",
    }

    for column in normalized.columns:
        if column in metadata_columns:
            continue

        if column not in baseline_means:
            raise ValueError(
                f"Missing baseline mean for channel: {column}"
            )

        if column not in baseline_scales:
            raise ValueError(
                f"Missing baseline scale for channel: {column}"
            )

        scale = float(
            baseline_scales[column]
        )

        if not math.isfinite(scale) or scale <= 0:
            raise ValueError(
                f"Invalid baseline scale for channel "
                f"{column}: {scale}"
            )

        normalized[column] = (
            normalized[column].astype(float)
            - float(baseline_means[column])
        ) / scale

    return normalized


