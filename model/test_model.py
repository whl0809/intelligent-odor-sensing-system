def load_training_metadata() -> dict[str, Any]:
    if not METADATA_FILE.is_file():
        raise FileNotFoundError(
            f"Cannot find training metadata:\n"
            f"{METADATA_FILE}\n\n"
            "Run food_freshness_multitask.py first."
        )

    return json.loads(
        METADATA_FILE.read_text(
            encoding="utf-8"
        )
    )


def load_model_package(
    task_name: str,
) -> dict[str, Any]:
    model_path = MODEL_FILES[task_name]

    if not model_path.is_file():
        raise FileNotFoundError(
            f"Cannot find model for {task_name}:\n"
            f"{model_path}\n\n"
            "Run food_freshness_multitask.py first."
        )

    package = joblib.load(model_path)

    required_keys = {
        "task_name",
        "model_name",
        "model",
        "feature_columns",
        "classes",
        "window_size",
        "window_stride",
    }

    missing_keys = (
        required_keys - set(package)
    )

    if missing_keys:
        raise ValueError(
            f"{model_path.name} is missing "
            f"required key(s): "
            f"{sorted(missing_keys)}"
        )

    return package


def predict_one_task(
    task_name: str,
    model_package: dict[str, Any],
    feature_frame: pd.DataFrame,
) -> tuple[
    dict[str, Any],
    pd.DataFrame,
]:
    model = model_package["model"]
    feature_columns = list(
        model_package["feature_columns"]
    )

    missing_features = [
        feature
        for feature in feature_columns
        if feature not in feature_frame.columns
    ]

    if missing_features:
        raise ValueError(
            f"Test features for task {task_name} "
            f"are missing:\n"
            + "\n".join(
                missing_features
            )
        )

    model_input = feature_frame.reindex(
        columns=feature_columns
    )

    predicted_labels = model.predict(
        model_input
    )

    prediction_table = pd.DataFrame(
        {
            f"{task_name}_prediction": (
                predicted_labels
            ),
        }
    )

    overall_label: str
    confidence: float
    class_scores: dict[str, float]

    if hasattr(model, "predict_proba"):
        probabilities = model.predict_proba(
            model_input
        )

        class_names = [
            str(value)
            for value in model.classes_
        ]

        mean_probabilities = (
            probabilities.mean(axis=0)
        )

        best_index = int(
            np.argmax(mean_probabilities)
        )

        overall_label = class_names[
            best_index
        ]
        confidence = float(
            mean_probabilities[best_index]
        )

        class_scores = {
            class_name: float(
                mean_probabilities[index]
            )
            for index, class_name
            in enumerate(class_names)
        }

        for index, class_name in enumerate(
            class_names
        ):
            prediction_table[
                f"{task_name}_probability_"
                f"{safe_name(class_name)}"
            ] = probabilities[:, index]

        aggregation_method = (
            "mean_window_probability"
        )

    else:
        counts = Counter(
            str(value)
            for value in predicted_labels
        )

        overall_label, winning_count = (
            counts.most_common(1)[0]
        )

        confidence = (
            winning_count
            / len(predicted_labels)
        )

        class_scores = {
            class_name: (
                count
                / len(predicted_labels)
            )
            for class_name, count
            in counts.items()
        }

        aggregation_method = (
            "majority_window_vote"
        )

    summary = {
        "task": task_name,
        "model_name": str(
            model_package["model_name"]
        ),
        "overall_prediction": (
            overall_label
        ),
        "confidence": confidence,
        "aggregation_method": (
            aggregation_method
        ),
        "window_count": len(
            predicted_labels
        ),
        "class_scores": class_scores,
    }

    return summary, prediction_table


# =============================================================================
# Main
# =============================================================================

def main() -> None:
    print("E-nose model test")
    print("=" * 72)
    print(f"Test CSV: {TEST_CSV.resolve()}")

    training_metadata = (
        load_training_metadata()
    )

    selected_channels = dict(
        training_metadata[
            "selected_channels"
        ]
    )
    baseline_means = {
        key: float(value)
        for key, value in training_metadata[
            "baseline_means"
        ].items()
    }
    baseline_scales = {
        key: float(value)
        for key, value in training_metadata[
            "baseline_scales"
        ].items()
    }

    model_packages = {
        task_name: load_model_package(
            task_name
        )
        for task_name in MODEL_FILES
    }

    window_sizes = {
        int(package["window_size"])
        for package in (
            model_packages.values()
        )
    }
    window_strides = {
        int(package["window_stride"])
        for package in (
            model_packages.values()
        )
    }

    if len(window_sizes) != 1:
        raise ValueError(
            "The three models use different "
            "window sizes."
        )

    if len(window_strides) != 1:
        raise ValueError(
            "The three models use different "
            "window strides."
        )

    window_size = window_sizes.pop()
    window_stride = (
        window_strides.pop()
    )

    raw_frame = read_test_csv(TEST_CSV)
    clean_frame = filter_valid_rows(
        raw_frame,
        selected_channels,
    )
    normalized_frame = (
        normalize_sensor_frame(
            clean_frame,
            baseline_means,
            baseline_scales,
        )
    )

    sensor_names = list(
        selected_channels
    )

    feature_frame, window_metadata = (
        create_test_windows(
            normalized_frame,
            sensor_names,
            window_size,
            window_stride,
        )
    )

    print("\nPreprocessing summary")
    print("-" * 72)
    print(
        f"Raw rows:          "
        f"{len(raw_frame)}"
    )
    print(
        f"Valid rows:        "
        f"{len(clean_frame)}"
    )
    print(
        f"Selected channels: "
        f"{sensor_names}"
    )
    print(
        f"Window size:       "
        f"{window_size}"
    )
    print(
        f"Window stride:     "
        f"{window_stride}"
    )
    print(
        f"Test windows:      "
        f"{len(feature_frame)}"
    )

    combined_window_output = (
        window_metadata.copy()
    )
    overall_results: dict[
        str,
        Any,
    ] = {
        "test_csv": str(
            TEST_CSV.resolve()
        ),
        "raw_rows": len(raw_frame),
        "valid_rows": len(clean_frame),
        "window_count": len(
            feature_frame
        ),
        "selected_channels": (
            selected_channels
        ),
        "predictions": {},
    }

    print("\nPredictions")
    print("=" * 72)

    for task_name in [
        "food_type",
        "freshness",
        "combined_class",
    ]:
        summary, task_window_output = (
            predict_one_task(
                task_name,
                model_packages[task_name],
                feature_frame,
            )
        )

        overall_results[
            "predictions"
        ][task_name] = summary

        combined_window_output = pd.concat(
            [
                combined_window_output,
                task_window_output,
            ],
            axis=1,
        )

        print(
            f"\nTask: {task_name}"
        )
        print(
            f"Model: "
            f"{summary['model_name']}"
        )
        print(
            f"Prediction: "
            f"{summary['overall_prediction']}"
        )
        print(
            f"Confidence: "
            f"{summary['confidence']:.4f}"
        )

        for class_name, score in (
            summary[
                "class_scores"
            ].items()
        ):
            print(
                f"  {class_name}: "
                f"{score:.4f}"
            )

    TEST_OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    combined_window_output.to_csv(
        WINDOW_OUTPUT_FILE,
        index=False,
    )

    SUMMARY_OUTPUT_FILE.write_text(
        json.dumps(
            overall_results,
            indent=2,
        ),
        encoding="utf-8",
    )

    print("\nSaved outputs")
    print("=" * 72)
    print(
        f"Window predictions:\n"
        f"  {WINDOW_OUTPUT_FILE.resolve()}"
    )
    print(
        f"Overall prediction:\n"
        f"  {SUMMARY_OUTPUT_FILE.resolve()}"
    )

    combined_prediction = (
        overall_results[
            "predictions"
        ]["combined_class"][
            "overall_prediction"
        ]
    )
    food_prediction = (
        overall_results[
            "predictions"
        ]["food_type"][
            "overall_prediction"
        ]
    )
    freshness_prediction = (
        overall_results[
            "predictions"
        ]["freshness"][
            "overall_prediction"
        ]
    )

    print("\nFinal result")
    print("=" * 72)
    print(
        f"Food type:      "
        f"{food_prediction}"
    )
    print(
        f"Freshness:      "
        f"{freshness_prediction}"
    )
    print(
        f"Combined class: "
        f"{combined_prediction}"
    )

    expected_combined = (
        f"{freshness_prediction}_"
        f"{food_prediction}"
    )

    if (
        combined_prediction
        != expected_combined
    ):
        print(
            "\nConsistency warning:"
        )
        print(
            "The combined-class model does not "
            "agree with the separate food-type "
            "and freshness models."
        )
        print(
            f"Separate predictions imply: "
            f"{expected_combined}"
        )


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print("\nERROR")
        print("=" * 72)
        print(error)
        raise
