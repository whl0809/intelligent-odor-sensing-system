# Feature extraction
# This must remain identical to the training code.
# =============================================================================

def safe_name(value: str) -> str:
    return re.sub(
        r"[^a-zA-Z0-9_]+",
        "_",
        value,
    ).strip("_").lower()


def safe_auc(values: np.ndarray) -> float:
    if hasattr(np, "trapezoid"):
        return float(
            np.trapezoid(values)
        )

    return float(np.trapz(values))


def safe_correlation(
    first: np.ndarray,
    second: np.ndarray,
) -> float:
    if len(first) < 2:
        return 0.0

    if (
        np.std(first) < 1e-12
        or np.std(second) < 1e-12
    ):
        return 0.0

    value = float(
        np.corrcoef(first, second)[0, 1]
    )

    return (
        value
        if math.isfinite(value)
        else 0.0
    )


def extract_features_from_window(
    window: pd.DataFrame,
    sensor_names: list[str],
) -> dict[str, float]:
    features: dict[str, float] = {}
    x_axis = np.arange(
        len(window),
        dtype=float,
    )

    for sensor_name in sensor_names:
        values = window[
            sensor_name
        ].to_numpy(dtype=float)

        prefix = safe_name(sensor_name)

        features[f"{prefix}_mean"] = float(
            np.mean(values)
        )
        features[f"{prefix}_std"] = float(
            np.std(values, ddof=0)
        )
        features[f"{prefix}_min"] = float(
            np.min(values)
        )
        features[f"{prefix}_max"] = float(
            np.max(values)
        )
        features[f"{prefix}_median"] = float(
            np.median(values)
        )
        features[f"{prefix}_q25"] = float(
            np.quantile(values, 0.25)
        )
        features[f"{prefix}_q75"] = float(
            np.quantile(values, 0.75)
        )
        features[f"{prefix}_range"] = float(
            np.max(values)
            - np.min(values)
        )
        features[
            f"{prefix}_last_minus_first"
        ] = float(
            values[-1] - values[0]
        )
        features[f"{prefix}_auc"] = (
            safe_auc(values)
        )
        features[f"{prefix}_slope"] = float(
            np.polyfit(
                x_axis,
                values,
                1,
            )[0]
        )

    for first_index in range(
        len(sensor_names)
    ):
        for second_index in range(
            first_index + 1,
            len(sensor_names),
        ):
            first_name = (
                sensor_names[first_index]
            )
            second_name = (
                sensor_names[second_index]
            )

            feature_name = (
                f"corr_{safe_name(first_name)}_"
                f"{safe_name(second_name)}"
            )

            features[feature_name] = (
                safe_correlation(
                    window[
                        first_name
                    ].to_numpy(dtype=float),
                    window[
                        second_name
                    ].to_numpy(dtype=float),
                )
            )

    tgs_names = [
        sensor_name
        for sensor_name in sensor_names
        if sensor_name.startswith("tgs")
    ]

    if tgs_names:
        tgs_window_means = np.array(
            [
                float(
                    window[
                        sensor_name
                    ].mean()
                )
                for sensor_name in tgs_names
            ],
            dtype=float,
        )

        features["tgs_array_mean"] = float(
            np.mean(tgs_window_means)
        )
        features[
            "tgs_array_std_between_sensors"
        ] = float(
            np.std(
                tgs_window_means,
                ddof=0,
            )
        )
        features[
            "tgs_array_range_between_sensors"
        ] = float(
            np.max(tgs_window_means)
            - np.min(tgs_window_means)
        )

    if (
        "nh3" in sensor_names
        and "h2s" in sensor_names
    ):
        features[
            "nh3_minus_h2s_mean"
        ] = float(
            window["nh3"].mean()
            - window["h2s"].mean()
        )

    return features


def create_test_windows(
    normalized_frame: pd.DataFrame,
    sensor_names: list[str],
    window_size: int,
    window_stride: int,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    if len(normalized_frame) < window_size:
        raise ValueError(
            f"Test CSV has only {len(normalized_frame)} valid rows, "
            f"but the trained model requires at least "
            f"{window_size} rows."
        )

    feature_rows: list[dict[str, float]] = []
    window_metadata: list[dict[str, Any]] = []

    for start in range(
        0,
        len(normalized_frame)
        - window_size
        + 1,
        window_stride,
    ):
        stop = start + window_size
        window = normalized_frame.iloc[
            start:stop
        ]

        feature_rows.append(
            extract_features_from_window(
                window,
                sensor_names,
            )
        )

        metadata_row: dict[str, Any] = {
            "window_index": len(
                window_metadata
            ),
            "window_start_row": start,
            "window_end_row": stop - 1,
        }

        if (
            "timestamp_utc"
            in normalized_frame.columns
        ):
            start_timestamp = (
                normalized_frame.iloc[
                    start
                ]["timestamp_utc"]
            )
            end_timestamp = (
                normalized_frame.iloc[
                    stop - 1
                ]["timestamp_utc"]
            )

            metadata_row[
                "window_start_timestamp"
            ] = str(start_timestamp)
            metadata_row[
                "window_end_timestamp"
            ] = str(end_timestamp)

        if (
            "elapsed_s"
            in normalized_frame.columns
        ):
            metadata_row[
                "window_start_elapsed_s"
            ] = float(
                normalized_frame.iloc[
                    start
                ]["elapsed_s"]
            )
            metadata_row[
                "window_end_elapsed_s"
            ] = float(
                normalized_frame.iloc[
                    stop - 1
                ]["elapsed_s"]
            )

        window_metadata.append(
            metadata_row
        )

    return (
        pd.DataFrame(feature_rows),
        pd.DataFrame(window_metadata),
    )


